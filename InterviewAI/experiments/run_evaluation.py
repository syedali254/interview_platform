"""Evaluation harness for the M6 LLM-as-Judge answer evaluator.

Runs the four controlled experiments that evidence Objective 6, writes the raw
per-answer records and the computed statistics to experiments/results/, and
renders the figures used in the dissertation.

    python -m experiments.run_evaluation                # full run
    python -m experiments.run_evaluation --quick        # smaller sample
    python -m experiments.run_evaluation --figures-only # re-render from cache

Experiments
-----------
E1  Discriminant validity
    Answers written at three known quality levels (strong / medium / weak) are
    scored blind. Agreement with the intended level is reported as Spearman's
    rho and quadratic weighted Cohen's Kappa.

E2  Positional-bias ablation
    Every answer is scored twice, once under each rubric ordering. The paired
    difference tests whether presentation order shifts the score (Stureborg et
    al., 2024) and quantifies how much averaging the two removes.

E3  Paraphrase invariance
    Semantically equivalent rewrites of the same answer should receive the same
    score. Within-group standard deviation measures how far that holds.

E4  Criterion independence
    The rubric instructs the judge to score four criteria independently. The
    correlation matrix between them tests whether it complies or collapses them
    into a single impression (halo effect).

E5  Verbosity probe
    A good answer padded with contentless filler should not score higher
    (Wang et al., 2024).

Nothing here is cached between statistics and figures: --figures-only re-reads
the JSON written by a previous full run, so figures can be restyled without
re-spending API calls.
"""

