# Ordinal quality levels, ranked worst to best for correlation.
LEVELS = ["weak", "medium", "strong"]
LEVEL_RANK = {level: i for i, level in enumerate(LEVELS)}

# Score bands each quality level is expected to land in. Used to convert the
# judge's continuous score to an ordinal category for Cohen's Kappa.
BAND_EDGES = (40.0, 70.0)  # < 40 weak, 40-70 medium, >= 70 strong

TOPICS_FULL = [
    "Python", "SQL", "REST APIs", "Docker", "Git",
    "Object-Oriented Programming", "Data Structures", "Testing",
    "Database Design", "Caching", "Authentication", "Microservices",
]
TOPICS_QUICK = TOPICS_FULL[:6]

PARAPHRASE_TOPICS_FULL = TOPICS_FULL[:6]
PARAPHRASE_TOPICS_QUICK = TOPICS_FULL[:3]

# Test fixtures are generated by a cheaper non-reasoning model. Two reasons.
# Cost: the generation prompts ask for long prose that needs no deliberation,
# and paying reasoning tokens for it is waste — measured at 0 thinking tokens
# and 1.8 s per call here, against a reasoning model's 20 s and change.
# Method: fixtures written by a different model than the one grading them
# weaken the objection that the judge is merely recognising its own prose.
#
# The generated fixtures are persisted to results/raw_scores.json, so the
# experiment remains reproducible from that file even after the generating
# model is retired — as gemini-2.0-flash was during this project.
GEN_MODEL = "gemini-flash-lite-latest"

# Measured on the free-tier Gemini endpoint: one call sequentially takes ~2.3 s,
# but six issued concurrently took 273.8 s in total. The endpoint throttles
# concurrency far harder than it throttles rate, so the harness runs serially.
# Raise this only against a paid endpoint with a known concurrency allowance.
MAX_WORKERS = 1


# ── Helpers ──────────────────────────────────────────────────────────────

def log(msg: str):
    print(f"[eval] {msg}", flush=True)


def band(score: float) -> int:
    """Map a 0-100 score onto the ordinal quality bands."""
    if score < BAND_EDGES[0]:
        return 0
    if score < BAND_EDGES[1]:
        return 1
    return 2


def parallel(fn, items, desc=""):
    """Run fn over items concurrently, preserving order, tolerating failures."""
    done = {"n": 0}
    total = len(items)

    def wrapped(item):
        try:
            result = fn(item)
        except Exception as exc:
            print(f"[eval]   ! {type(exc).__name__}: {str(exc)[:120]}", flush=True)
            result = None
        done["n"] += 1
        if done["n"] % 5 == 0 or done["n"] == total:
            log(f"  {desc} {done['n']}/{total}")
        return result

    with ThreadPoolExecutor(max_workers=MAX_WORKERS) as pool:
        return [r for r in pool.map(wrapped, items) if r is not None]


# ── Data generation ──────────────────────────────────────────────────────

def generate_item(topic: str) -> dict:
    """One question with a reference answer and three graded candidate answers."""
    prompt = f"""Write one technical interview question about {topic}, then write
three candidate answers to it at three distinct quality levels.

The three answers must be clearly separable in quality but all must be a genuine
attempt at the question. Write them as a candidate would speak them aloud.

Return ONLY this JSON:
{{
  "question": "the interview question",
  "skill": "{topic}",
  "strong_answer": "An excellent answer: accurate, covers the core concepts, well structured (80-140 words)",
  "medium_answer": "A partially correct answer: broadly right but incomplete or imprecise (50-90 words)",
  "weak_answer": "A poor answer: vague, largely wrong, or showing minimal understanding (20-50 words)"
}}"""
    data = call_llm_json(prompt, temperature=0.7, model=GEN_MODEL)
    required = ("question", "strong_answer", "medium_answer", "weak_answer")
    if not all(data.get(k) for k in required):
        raise ValueError(f"incomplete generation for {topic}")
    return {
        "topic": topic,
        "question": data["question"],
        "answers": {level: data[f"{level}_answer"] for level in LEVELS},
    }


def generate_paraphrases(question: str, answer: str, n: int = 2) -> list:
    """Semantically equivalent rewrites of one answer."""
    prompt = f"""Rewrite this interview answer {n} times.

Each rewrite must preserve the exact same technical content, the same level of
detail and the same concepts — change only the wording, sentence structure and
order of presentation. Do not add information. Do not remove information. Do not
make any version better or worse than the original.

QUESTION: {question}
ANSWER: {answer}

Return ONLY this JSON:
{{"paraphrases": ["first rewrite", "second rewrite"]}}"""
    data = call_llm_json(prompt, temperature=0.6, model=GEN_MODEL)
    out = data.get("paraphrases") or []
    return [p for p in out if isinstance(p, str) and p.strip()][:n]


def pad_with_filler(answer: str) -> str:
    """Append contentless verbiage — tests whether length alone buys score."""
    filler = (
        " I think that's really the main thing to say about it, and obviously "
        "there are lots of different ways people approach this kind of problem "
        "in practice. It's definitely something that comes up quite a lot and "
        "it's basically a really important area to understand properly. So yeah, "
        "that's essentially how I'd generally think about it overall."
    )
    return answer + filler


# ── Scoring ──────────────────────────────────────────────────────────────

def score_one(question: str, skill: str, answer: str, reference: str) -> dict:
    """Score one answer, returning the judge's full record."""
    judged = judge_answer(question, answer, skill, reference)
    return {
        "score": judged["score"],
        "call_scores": judged["call_scores"],
        "spread": judged["spread"],
        "consistency": judged["consistency"],
        "criterion_scores": judged["criterion_scores"],
    }


# ── Experiment runner ────────────────────────────────────────────────────

def run_experiments(quick: bool) -> dict:
    topics = TOPICS_QUICK if quick else TOPICS_FULL
    para_topics = PARAPHRASE_TOPICS_QUICK if quick else PARAPHRASE_TOPICS_FULL
    n_para = 2

    started = time.time()

    # ── Generate the question set ────────────────────────────────────────
    log(f"Generating {len(topics)} questions with graded answers...")
    items = parallel(generate_item, topics, "generated")
    log(f"Generated {len(items)} usable items")

    # ── Reference answers (one per question, reused across all levels) ────
    log("Generating reference answers...")

    def make_ref(item):
        item["reference"] = generate_reference_answer(item["question"], item["topic"])
        return item

    items = parallel(make_ref, items, "references")

    # ── E1 + E2 + E4: score every graded answer ──────────────────────────
    jobs = [
        {"item": item, "level": level, "answer": item["answers"][level]}
        for item in items for level in LEVELS
    ]
    log(f"Scoring {len(jobs)} graded answers (2 judge calls each)...")

    def run_graded(job):
        item = job["item"]
        rec = score_one(item["question"], item["topic"], job["answer"], item["reference"])
        rec.update({
            "topic": item["topic"],
            "question": item["question"],
            "level": job["level"],
            "expected_rank": LEVEL_RANK[job["level"]],
            "answer": job["answer"],
        })
        return rec

    graded = parallel(run_graded, jobs, "scored")

    # The strong answer of each question is already scored above. E3 and E5
    # both use it as their baseline, so they reuse that record rather than
    # paying to score identical text a second time. Besides the saving, it
    # keeps the baseline identical across the three experiments.
    strong_by_topic = {
        rec["topic"]: rec for rec in graded if rec["level"] == "strong"
    }

    # ── E3: paraphrase invariance ────────────────────────────────────────
    para_items = [it for it in items
                  if it["topic"] in para_topics and it["topic"] in strong_by_topic]
    log(f"Generating paraphrases for {len(para_items)} answers...")

    def make_paraphrases(item):
        original = item["answers"]["strong"]
        variants = generate_paraphrases(item["question"], original, n_para)
        if not variants:
            return None
        return {"item": item, "variants": variants}

    para_groups = parallel(make_paraphrases, para_items, "paraphrased")

    para_jobs = [
        {"group": g, "variant_index": i + 1, "text": text}
        for g in para_groups for i, text in enumerate(g["variants"])
    ]
    log(f"Scoring {len(para_jobs)} paraphrase variants "
        f"({len(para_groups)} originals reused from E1)...")

    def run_para(job):
        item = job["group"]["item"]
        rec = score_one(item["question"], item["topic"], job["text"], item["reference"])
        rec.update({
            "topic": item["topic"],
            "group": item["topic"],
            "variant_index": job["variant_index"],
            "is_original": False,
            "answer": job["text"],
        })
        return rec

    paraphrase = parallel(run_para, para_jobs, "scored")

    # Fold the reused originals back in so each group has a complete set.
    for group in para_groups:
        topic = group["item"]["topic"]
        base = strong_by_topic[topic]
        paraphrase.append({
            **{k: base[k] for k in
               ("score", "call_scores", "spread", "consistency", "criterion_scores")},
            "topic": topic,
            "group": topic,
            "variant_index": 0,
            "is_original": True,
            "answer": base["answer"],
            "reused_from": "e1_strong",
        })

    # ── E5: verbosity probe ──────────────────────────────────────────────
    log(f"Running verbosity probe on {len(para_items)} answers "
        f"(originals reused from E1)...")

    def run_verbosity(item):
        original = item["answers"]["strong"]
        padded = pad_with_filler(original)
        base = strong_by_topic[item["topic"]]
        pad = score_one(item["question"], item["topic"], padded, item["reference"])
        return {
            "topic": item["topic"],
            "original_score": base["score"],
            "padded_score": pad["score"],
            "delta": round(pad["score"] - base["score"], 2),
            "original_words": len(original.split()),
            "padded_words": len(padded.split()),
        }

    verbosity = parallel(run_verbosity, para_items, "probed")

    elapsed = time.time() - started
    usage = call_stats()
    log(f"All scoring complete in {elapsed/60:.1f} min")
    log(f"API usage: {usage['calls']} calls, {usage['by_model']}, "
        f"{usage['errors']} errors, {usage['seconds']:.0f}s in-flight")

    return {
        "meta": {
            "generated_at": time.strftime("%Y-%m-%d %H:%M:%S"),
            "quick_mode": quick,
            "n_questions": len(items),
            "n_graded_answers": len(graded),
            "n_paraphrase_scores": len(paraphrase),
            "n_verbosity_pairs": len(verbosity),
            "elapsed_seconds": round(elapsed, 1),
            "api_usage": usage,
            "rubric_orders": CRITERIA_ORDERS,
            "criteria": list(CRITERIA),
        },
        "graded": graded,
        "paraphrase": paraphrase,
        "verbosity": verbosity,
    }


# ── Statistics ───────────────────────────────────────────────────────────

def compute_statistics(raw: dict) -> dict:
    from scipy import stats as st
    from sklearn.metrics import cohen_kappa_score

    graded = raw["graded"]
    scores = np.array([g["score"] for g in graded], dtype=float)
    expected = np.array([g["expected_rank"] for g in graded], dtype=int)
    observed = np.array([band(s) for s in scores], dtype=int)

    # ── E1 Discriminant validity ─────────────────────────────────────────
    rho, rho_p = st.spearmanr(expected, scores)
    kappa = cohen_kappa_score(expected, observed, weights="quadratic")

    by_level = {}
    for level in LEVELS:
        vals = np.array([g["score"] for g in graded if g["level"] == level])
        by_level[level] = {
            "n": int(vals.size),
            "mean": round(float(vals.mean()), 2) if vals.size else None,
            "sd": round(float(vals.std(ddof=1)), 2) if vals.size > 1 else None,
            "min": round(float(vals.min()), 1) if vals.size else None,
            "max": round(float(vals.max()), 1) if vals.size else None,
        }

    strong = np.array([g["score"] for g in graded if g["level"] == "strong"])
    weak = np.array([g["score"] for g in graded if g["level"] == "weak"])
    medium = np.array([g["score"] for g in graded if g["level"] == "medium"])

    def cohens_d(a, b):
        if a.size < 2 or b.size < 2:
            return None
        pooled = np.sqrt(((a.size - 1) * a.var(ddof=1) + (b.size - 1) * b.var(ddof=1))
                         / (a.size + b.size - 2))
        return round(float((a.mean() - b.mean()) / pooled), 3) if pooled > 0 else None

    sw_u, sw_p = st.mannwhitneyu(strong, weak, alternative="greater") if strong.size and weak.size else (None, None)

    e1 = {
        "n": int(scores.size),
        "spearman_rho": round(float(rho), 4),
        "spearman_p": float(f"{rho_p:.3e}"),
        "quadratic_weighted_kappa": round(float(kappa), 4),
        "exact_band_agreement": round(float((expected == observed).mean()), 4),
        "within_one_band": round(float((np.abs(expected - observed) <= 1).mean()), 4),
        "by_level": by_level,
        "separation": {
            "strong_vs_weak_cohens_d": cohens_d(strong, weak),
            "strong_vs_medium_cohens_d": cohens_d(strong, medium),
            "medium_vs_weak_cohens_d": cohens_d(medium, weak),
            "mann_whitney_u_strong_gt_weak": float(sw_u) if sw_u is not None else None,
            "mann_whitney_p": float(f"{sw_p:.3e}") if sw_p is not None else None,
        },
    }

    # ── E2 Positional-bias ablation ──────────────────────────────────────
    order_a = np.array([g["call_scores"][0] for g in graded], dtype=float)
    order_b = np.array([g["call_scores"][1] for g in graded], dtype=float)
    diff = order_a - order_b
    spreads = np.abs(diff)

    try:
        w_stat, w_p = st.wilcoxon(order_a, order_b)
    except ValueError:  # all differences zero
        w_stat, w_p = 0.0, 1.0

    # How much does averaging two orderings reduce run-to-run variability?
    # SD of a single ordering vs SD of their mean, on the paired differences.
    single_sd = float(diff.std(ddof=1)) if diff.size > 1 else 0.0

    consistency_dist = {"high": 0, "moderate": 0, "low": 0}
    for g in graded:
        consistency_dist[g["consistency"]] = consistency_dist.get(g["consistency"], 0) + 1

    e2 = {
        "n": int(order_a.size),
        "order_a_mean": round(float(order_a.mean()), 2),
        "order_b_mean": round(float(order_b.mean()), 2),
        "mean_signed_difference": round(float(diff.mean()), 3),
        "mean_absolute_spread": round(float(spreads.mean()), 3),
        "median_absolute_spread": round(float(np.median(spreads)), 3),
        "max_absolute_spread": round(float(spreads.max()), 1),
        "sd_of_paired_difference": round(single_sd, 3),
        "sd_of_averaged_score_estimate": round(single_sd / 2.0, 3),
        "variance_reduction_from_averaging": "50% (SE of the mean of two draws)",
        "wilcoxon_statistic": float(w_stat),
        "wilcoxon_p": float(f"{w_p:.4f}"),
        "systematic_order_effect": bool(w_p < 0.05),
        "consistency_distribution": consistency_dist,
        "pct_flagged_low_consistency": round(
            100.0 * consistency_dist.get("low", 0) / max(len(graded), 1), 2),
    }

    # ── E3 Paraphrase invariance ─────────────────────────────────────────
    groups = {}
    for rec in raw["paraphrase"]:
        groups.setdefault(rec["group"], []).append(rec["score"])

    group_stats = []
    for name, vals in groups.items():
        arr = np.array(vals, dtype=float)
        if arr.size < 2:
            continue
        group_stats.append({
            "group": name,
            "n": int(arr.size),
            "mean": round(float(arr.mean()), 2),
            "sd": round(float(arr.std(ddof=1)), 2),
            "range": round(float(arr.max() - arr.min()), 1),
        })

    sds = np.array([g["sd"] for g in group_stats], dtype=float)
    ranges = np.array([g["range"] for g in group_stats], dtype=float)

    e3 = {
        "n_groups": len(group_stats),
        "variants_per_group": int(np.mean([g["n"] for g in group_stats])) if group_stats else 0,
        "mean_within_group_sd": round(float(sds.mean()), 3) if sds.size else None,
        "max_within_group_sd": round(float(sds.max()), 2) if sds.size else None,
        "mean_within_group_range": round(float(ranges.mean()), 2) if ranges.size else None,
        "max_within_group_range": round(float(ranges.max()), 1) if ranges.size else None,
        "groups": sorted(group_stats, key=lambda g: -g["sd"]),
    }
    # Between-group SD gives the scale against which within-group noise matters.
    if group_stats:
        between = np.array([g["mean"] for g in group_stats], dtype=float)
        e3["between_group_sd"] = round(float(between.std(ddof=1)), 2) if between.size > 1 else None

    # ── E4 Criterion independence ────────────────────────────────────────
    names = list(CRITERIA)
    matrix = np.array([[g["criterion_scores"][n] for n in names] for g in graded], dtype=float)
    corr = np.corrcoef(matrix, rowvar=False)

    pairs = []
    for i in range(len(names)):
        for j in range(i + 1, len(names)):
            pairs.append({
                "pair": f"{names[i]} / {names[j]}",
                "r": round(float(corr[i, j]), 4),
            })

    off_diagonal = [p["r"] for p in pairs]
    e4 = {
        "criteria": names,
        "correlation_matrix": [[round(float(v), 4) for v in row] for row in corr],
        "pairwise": sorted(pairs, key=lambda p: -p["r"]),
        "mean_inter_criterion_r": round(float(np.mean(off_diagonal)), 4),
        "min_inter_criterion_r": round(float(np.min(off_diagonal)), 4),
        "max_inter_criterion_r": round(float(np.max(off_diagonal)), 4),
        "criterion_means": {
            n: round(float(matrix[:, i].mean()), 2) for i, n in enumerate(names)
        },
        "criterion_sds": {
            n: round(float(matrix[:, i].std(ddof=1)), 2) for i, n in enumerate(names)
        },
    }

    # ── E5 Verbosity probe ───────────────────────────────────────────────
    deltas = np.array([v["delta"] for v in raw["verbosity"]], dtype=float)
    if deltas.size:
        try:
            v_stat, v_p = st.wilcoxon(deltas)
        except ValueError:
            v_stat, v_p = 0.0, 1.0
        e5 = {
            "n": int(deltas.size),
            "mean_delta": round(float(deltas.mean()), 3),
            "median_delta": round(float(np.median(deltas)), 2),
            "n_increased": int((deltas > 0).sum()),
            "n_decreased": int((deltas < 0).sum()),
            "n_unchanged": int((deltas == 0).sum()),
            "wilcoxon_p": float(f"{v_p:.4f}"),
            "rewards_padding": bool(v_p < 0.05 and deltas.mean() > 0),
            "pairs": raw["verbosity"],
        }
    else:
        e5 = {"n": 0}

    return {
        "meta": raw["meta"],
        "e1_discriminant_validity": e1,
        "e2_positional_bias": e2,
        "e3_paraphrase_invariance": e3,
        "e4_criterion_independence": e4,
        "e5_verbosity": e5,
    }


