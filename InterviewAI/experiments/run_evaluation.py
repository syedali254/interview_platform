def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--quick", action="store_true", help="smaller sample")
    parser.add_argument("--figures-only", action="store_true",
                        help="recompute statistics and figures from cached raw scores")
    args = parser.parse_args()

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    reset_call_stats()

    if args.figures_only:
        if not RAW_PATH.exists():
            print(f"No cached results at {RAW_PATH}. Run without --figures-only first.")
            return 1
        raw = json.loads(RAW_PATH.read_text(encoding="utf-8"))
        log(f"Loaded {len(raw['graded'])} cached graded scores")
    else:
        raw = run_experiments(quick=args.quick)
        RAW_PATH.write_text(json.dumps(raw, indent=2), encoding="utf-8")
        log(f"Raw scores written to {RAW_PATH}")

    stats = compute_statistics(raw)
    STATS_PATH.write_text(json.dumps(stats, indent=2), encoding="utf-8")
    log(f"Statistics written to {STATS_PATH}")

    render_figures(raw, stats)
    print_summary(stats)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
